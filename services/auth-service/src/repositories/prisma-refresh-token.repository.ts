import { type PrismaClient } from '../generated/prisma/client';

import { selectExecutor } from './prisma-transaction';
import {
  type CreateRefreshTokenInput,
  type RefreshTokenRecord,
  type RefreshTokenRepository,
} from './refresh-token.repository';
import { type Transaction } from './transaction';

/** `RefreshTokenRepository` backed by Prisma. */
export class PrismaRefreshTokenRepository implements RefreshTokenRepository {
  /**
   * @param client - The shared Prisma client, used for reads outside a transaction.
   */
  constructor(private readonly client: PrismaClient) {}

  /**
   * Stores a new token. Its id is generated by the database.
   *
   * @param input - The token's data. Never the raw token, only its hash.
   * @param tx - The open transaction.
   * @returns The stored token.
   */
  create(input: CreateRefreshTokenInput, tx: Transaction): Promise<RefreshTokenRecord> {
    return selectExecutor(this.client, tx).refreshToken.create({ data: input });
  }

  /**
   * @param tokenHash - SHA-256 of the presented token, lower-case hex.
   * @param tx - Transaction to read in, when the call is part of one.
   * @returns The token, or null when none matches.
   */
  findByTokenHash(tokenHash: string, tx?: Transaction): Promise<RefreshTokenRecord | null> {
    return selectExecutor(this.client, tx).refreshToken.findUnique({ where: { tokenHash } });
  }

  /**
   * Marks a token as replaced by its successor, only while it is neither rotated nor revoked.
   *
   * @param id - The token being rotated.
   * @param replacedById - The successor's id.
   * @param rotatedAt - When the rotation happened.
   * @param tx - The open transaction.
   * @returns True when this call performed the rotation, false when it was already rotated or revoked.
   */
  async markRotated(
    id: string,
    replacedById: string,
    rotatedAt: Date,
    tx: Transaction,
  ): Promise<boolean> {
    const result = await selectExecutor(this.client, tx).refreshToken.updateMany({
      where: { id, rotatedAt: null, revokedAt: null },
      data: { rotatedAt, replacedById },
    });
    return result.count > 0;
  }

  /**
   * Revokes every still-active token of one login.
   *
   * @param familyId - The login's family id.
   * @param revokedAt - When the revocation happened.
   * @param tx - The open transaction.
   * @returns How many tokens were newly revoked.
   */
  async revokeFamily(familyId: string, revokedAt: Date, tx: Transaction): Promise<number> {
    const result = await selectExecutor(this.client, tx).refreshToken.updateMany({
      where: { familyId, revokedAt: null },
      data: { revokedAt },
    });
    return result.count;
  }

  /**
   * Revokes every still-active token of a user.
   *
   * @param userId - The user's id.
   * @param revokedAt - When the revocation happened.
   * @param tx - The open transaction.
   * @returns How many tokens were newly revoked.
   */
  async revokeAllForUser(userId: string, revokedAt: Date, tx: Transaction): Promise<number> {
    const result = await selectExecutor(this.client, tx).refreshToken.updateMany({
      where: { userId, revokedAt: null },
      data: { revokedAt },
    });
    return result.count;
  }

  /**
   * Deletes tokens that expired before a cutoff, oldest first, in a bounded batch.
   *
   * @param before - Tokens with `expiresAt` earlier than this are deleted.
   * @param limit - Maximum number of rows to delete in this call.
   * @param tx - The open transaction.
   * @returns How many tokens were deleted.
   */
  async deleteExpired(before: Date, limit: number, tx: Transaction): Promise<number> {
    const executor = selectExecutor(this.client, tx);
    // Prisma's deleteMany has no LIMIT, so pick the batch first.
    const expired = await executor.refreshToken.findMany({
      where: { expiresAt: { lt: before } },
      orderBy: { expiresAt: 'asc' },
      take: limit,
      select: { id: true },
    });
    const result = await executor.refreshToken.deleteMany({
      where: { id: { in: expired.map((token) => token.id) } },
    });
    return result.count;
  }
}
