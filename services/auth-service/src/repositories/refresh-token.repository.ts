import { type Transaction } from './transaction';

/** A row of `refresh_tokens`, as the rest of the service sees it. */
export interface RefreshTokenRecord {
  readonly id: string;
  readonly userId: string;
  /** Shared by every token issued from one login. */
  readonly familyId: string;
  /** SHA-256 of the opaque token, lower-case hex. */
  readonly tokenHash: string;
  /** When the user last entered their password; copied unchanged on rotation. */
  readonly authTime: Date;
  readonly expiresAt: Date;
  /** Set when a successor was issued. */
  readonly rotatedAt: Date | null;
  readonly replacedById: string | null;
  readonly revokedAt: Date | null;
  readonly userAgent: string | null;
  readonly ip: string | null;
  readonly createdAt: Date;
}

export interface CreateRefreshTokenInput {
  readonly userId: string;
  readonly familyId: string;
  /** SHA-256 of the opaque token, lower-case hex (64 characters). */
  readonly tokenHash: string;
  readonly authTime: Date;
  readonly expiresAt: Date;
  /** Truncate to 512 characters before calling. */
  readonly userAgent: string | null;
  readonly ip: string | null;
}

/** Storage for refresh tokens. Only this repository writes to `refresh_tokens`. */
export interface RefreshTokenRepository {
  /**
   * Stores a new token. Its id is generated by the database.
   *
   * @param input - The token's data. Never the raw token, only its hash.
   * @param tx - The open transaction.
   * @returns The stored token.
   */
  create(input: CreateRefreshTokenInput, tx: Transaction): Promise<RefreshTokenRecord>;

  /**
   * @param tokenHash - SHA-256 of the presented token, lower-case hex.
   * @param tx - Transaction to read in, when the call is part of one.
   * @returns The token, or null when none matches.
   */
  findByTokenHash(tokenHash: string, tx?: Transaction): Promise<RefreshTokenRecord | null>;

  /**
   * Marks a token as replaced by its successor. This is a guarded transition: it only happens
   * while the token is neither rotated nor revoked, so of two concurrent callers exactly one wins.
   *
   * @param id - The token being rotated.
   * @param replacedById - The successor's id.
   * @param rotatedAt - When the rotation happened.
   * @param tx - The open transaction.
   * @returns True when this call performed the rotation, false when it was already rotated or revoked.
   */
  markRotated(id: string, replacedById: string, rotatedAt: Date, tx: Transaction): Promise<boolean>;

  /**
   * Revokes every still-active token of one login (used when a rotated token is replayed).
   *
   * @param familyId - The login's family id.
   * @param revokedAt - When the revocation happened.
   * @param tx - The open transaction.
   * @returns How many tokens were newly revoked.
   */
  revokeFamily(familyId: string, revokedAt: Date, tx: Transaction): Promise<number>;

  /**
   * Revokes every still-active token of a user (password change or reset, account disabled).
   *
   * @param userId - The user's id.
   * @param revokedAt - When the revocation happened.
   * @param tx - The open transaction.
   * @returns How many tokens were newly revoked.
   */
  revokeAllForUser(userId: string, revokedAt: Date, tx: Transaction): Promise<number>;

  /**
   * Deletes tokens that expired before a cutoff, oldest first, in a bounded batch.
   *
   * @param before - Tokens with `expiresAt` earlier than this are deleted.
   * @param limit - Maximum number of rows to delete in this call.
   * @param tx - The open transaction.
   * @returns How many tokens were deleted.
   */
  deleteExpired(before: Date, limit: number, tx: Transaction): Promise<number>;
}
